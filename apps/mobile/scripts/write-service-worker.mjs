// Writes the web app's service worker into an exported web build (ADR-0019):
//   node scripts/write-service-worker.mjs dist
// Runs after `expo export --platform web` (see the `build:web` script). The worker precaches every
// file of the build, so the app starts without a connection; the version is a hash of the files,
// so every new build installs a new worker.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const distDir = process.argv[2];
if (!distDir) {
  console.error('usage: node scripts/write-service-worker.mjs <dist dir>');
  process.exit(1);
}

const SKIPPED = /(^sw\.js$|\.map$|^metadata\.json$)/;

function listFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

const files = listFiles(distDir)
  .map((path) => ({ path, url: `/${relative(distDir, path).split(sep).join('/')}` }))
  .filter(({ url }) => !SKIPPED.test(url.slice(1)))
  .sort((a, b) => a.url.localeCompare(b.url));

const hash = createHash('sha256');
for (const { path, url } of files) {
  hash.update(url);
  hash.update(readFileSync(path));
}
const version = hash.digest('hex').slice(0, 16);
const urls = files.map(({ url }) => url);

const worker = `// Generated by scripts/write-service-worker.mjs — do not edit.
// Italština RICI web app (ADR-0019): the app shell works offline; lessons, progress and the
// session live in IndexedDB / localStorage, never in this cache.
const CACHE = 'rici-app-${version}';
const PRECACHE = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', (event) => {
  // A new version waits until every window of the old one is closed, so a running app never
  // loads files of another build.
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key.startsWith('rici-app-') && key !== CACHE).map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  // The API is always asked live; the app keeps what it needs offline itself.
  if (url.pathname.startsWith('/api/')) return;
  if (request.mode === 'navigate') {
    // Every page of the single-page app is index.html; offline first, the update comes with the
    // next version of this worker.
    event.respondWith(
      caches.match('/index.html').then((cached) => cached ?? fetch(request)),
    );
    return;
  }
  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ??
        fetch(request).then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone();
            void caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;

writeFileSync(join(distDir, 'sw.js'), worker);
console.log(`service worker: ${urls.length} files, version ${version}`);
